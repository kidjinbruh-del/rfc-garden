function apply() {
    document.documentElement.lang = lang === "en" ? "en" : "ru";
    // <title data-i18n="...">
    var titleEl = document.querySelector("title[data-i18n]");
    if (titleEl) document.title = t(titleEl.getAttribute("data-i18n"), titleEl.textContent);
    // переключатель языка
    var tb = document.getElementById("langToggle");
    if (tb) {
        tb.textContent = lang === "ru" ? "EN" : "RU";
        tb.setAttribute("aria-label", lang === "ru" ? t("lang.aria.ru") : t("lang.aria.en"));
    }
    if (lang !== "en") return;
    // атрибуты: data-i18n-attr="aria-label:key|title:key2|placeholder:key3"
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
        String(el.getAttribute("data-i18n-attr") || "").split("|").forEach(function (pair) {
            var ai = pair.split(":");
            var name = ai.shift();
            var key = ai.join(":");
            if (!name || !key) return;
            el.setAttribute(name, t(key));
        });
    });
    // текст с HTML
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
        el.innerHTML = t(el.getAttribute("data-i18n-html"), el.innerHTML);
    });
    // простой текст
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        el.textContent = t(el.getAttribute("data-i18n"), el.textContent);
    });
}

