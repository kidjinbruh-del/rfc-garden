function t(key, fallback) {
    if (lang === "en") {
        if (D.hasOwnProperty(key) && D[key]) return D[key];
        return fallback !== undefined ? fallback : key;
    }
    return fallback !== undefined ? fallback : key;
}

function apply() {
    document.documentElement.lang = lang === "en" ? "en" : "ru";
    // <title data-i18n="...">
    var titleEl = document.querySelector("title[data-i18n]");
    if (titleEl) document.title = t(titleEl.getAttribute("data-i18n"), titleEl.textContent);
    // переключатель языка
    var tb = document.getElementById("langToggle");
    if (tb) {
        tb.textContent = lang === "ru" ? "EN" : "RU";
        tb.setAttribute("aria-label", lang === "ru" ? t("lang.aria.ru") : t("lang.aria.en"));
    }
    if (lang !== "en") return;
    // атрибуты: data-i18n-attr="aria-label:key|title:key2|placeholder:key3"
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
        String(el.getAttribute("data-i18n-attr") || "").split("|").forEach(function (pair) {
            var ai = pair.split(":");
            var name = ai.shift();
            var key = ai.join(":");
            if (!name || !key) return;
            el.setAttribute(name, t(key));
        });
    });
    // текст с HTML
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
        el.innerHTML = t(el.getAttribute("data-i18n-html"), el.innerHTML);
    });
    // простой текст
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        el.textContent = t(el.getAttribute("data-i18n"), el.textContent);
    });
}

function toggle() {
    lang = lang === "ru" ? "en" : "ru";
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
    location.reload();
}

// apply() в конце body (скрипты стоят в конце): DOM уже готов
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", apply);
} else {
    apply();
}

window.I18N = { t: t, apply: apply, toggle: toggle, get lang() { return lang; } };

var lt = document.getElementById("langToggle");
if (lt) lt.addEventListener("click", toggle);

